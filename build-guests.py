#!/usr/bin/env python3
"""Build a compact guest allowlist (guests-data.js) from the wedding guest list.

Usage (from this folder, with the spreadsheet one level up):
  python3 build-guests.py
  python3 build-guests.py "/path/to/Wedding Guest List.xlsx"

Requires: openpyxl  (pip install openpyxl)
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

try:
    import openpyxl
except ImportError:
    sys.stderr.write(
        "Missing openpyxl. Install with:\n"
        "  python3 -m pip install openpyxl\n"
    )
    sys.exit(1)

HERE = Path(__file__).resolve().parent
DEFAULT_XLSX = HERE.parent / "Wedding Guest List.xlsx"
OUT = HERE / "guests-data.js"

# Header row on the Guest List sheet (1-indexed).
HEADER_ROW = 6
COL_NAME = 2
COL_RSVP = 4
COL_TIER = 5

# Eligibility: anyone named on the Guest List may unlock, including RSVP
# blank / not-yet. Only clear declines are excluded.
DECLINED = {
    "no",
    "n",
    "declined",
    "decline",
    "regretfully declines",
    "not attending",
    "can't attend",
    "cannot attend",
    "won't attend",
    "will not attend",
}


def norm_space(value: object) -> str:
    return re.sub(r"\s+", " ", str(value or "")).strip()


def is_declined(rsvp: object) -> bool:
    if rsvp is None:
        return False
    return norm_space(rsvp).lower() in DECLINED


def find_email_column(ws) -> int | None:
    """Optional Email column if added later to the spreadsheet."""
    for col in range(1, (ws.max_column or 0) + 1):
        header = norm_space(ws.cell(HEADER_ROW, col).value).lower()
        if header in {"email", "e-mail", "email address"}:
            return col
    return None


def load_guests(xlsx: Path) -> list[dict]:
    wb = openpyxl.load_workbook(xlsx, data_only=True)
    if "Guest List" not in wb.sheetnames:
        raise SystemExit(f"No 'Guest List' sheet in {xlsx}")
    ws = wb["Guest List"]
    email_col = find_email_column(ws)

    guests: list[dict] = []
    seen_keys: set[tuple[str, str]] = set()

    for row in range(HEADER_ROW + 1, (ws.max_row or 0) + 1):
        name = norm_space(ws.cell(row, COL_NAME).value)
        if not name:
            continue
        if is_declined(ws.cell(row, COL_RSVP).value):
            continue

        email = ""
        if email_col:
            email = norm_space(ws.cell(row, email_col).value).lower()
            if email and "@" not in email:
                email = ""

        tier_raw = ws.cell(row, COL_TIER).value
        tier = None
        if tier_raw is not None and str(tier_raw).strip() != "":
            try:
                tier = int(tier_raw)
            except (TypeError, ValueError):
                tier = str(tier_raw).strip()

        key = (name.lower(), email)
        if key in seen_keys:
            continue
        seen_keys.add(key)

        entry: dict = {"n": name}
        if email:
            entry["e"] = email
        if tier is not None:
            entry["t"] = tier
        guests.append(entry)

    return guests


def write_js(guests: list[dict], out: Path) -> None:
    payload = json.dumps(guests, ensure_ascii=False, separators=(",", ":"))
    text = (
        "/* Auto-generated by build-guests.py — do not edit by hand.\n"
        "   Compact allowlist for the invitation gate (name / optional email / tier).\n"
        "   Regenerate after updating the Wedding Guest List spreadsheet. */\n"
        "window.WEDDING_GUESTS = "
        + payload
        + ";\n"
    )
    out.write_text(text, encoding="utf-8")


def main() -> None:
    xlsx = Path(sys.argv[1]).expanduser().resolve() if len(sys.argv) > 1 else DEFAULT_XLSX
    if not xlsx.is_file():
        raise SystemExit(f"Guest list not found: {xlsx}")

    guests = load_guests(xlsx)
    write_js(guests, OUT)
    with_email = sum(1 for g in guests if g.get("e"))
    print(f"Wrote {len(guests)} guests ({with_email} with email) → {OUT.name}")


if __name__ == "__main__":
    main()
